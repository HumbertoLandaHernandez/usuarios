-- Esquema "Sistema" convertido de SQL Server (Generica.Sistema) a PostgreSQL.
--
-- Equivalencias de tipos:
--   tinyint                    -> smallint      (PostgreSQL no tiene tinyint)
--   datetime2(7)               -> timestamp(6)  (precisión máxima en PostgreSQL)
--   timestamp / rowversion     -> integer, que se incrementa con un trigger en cada UPDATE
--   collation Modern_Spanish_CI_AS (sin distinguir mayúsculas) -> índices sobre lower(...)
--
-- Los *Usys guardan el usuario que hizo el último cambio; los *DT, la fecha del último cambio.

CREATE SCHEMA IF NOT EXISTS "Sistema";

-- Actualiza en cada UPDATE una columna de fecha ('dt') o de versión ('rv').
CREATE OR REPLACE FUNCTION "Sistema".tg_auditoria() RETURNS trigger AS $$
BEGIN
  IF TG_ARGV[1] = 'rv' THEN
    NEW := jsonb_populate_record(NEW, jsonb_build_object(TG_ARGV[0], (to_jsonb(OLD) ->> TG_ARGV[0])::int + 1));
  ELSE
    NEW := jsonb_populate_record(NEW, jsonb_build_object(TG_ARGV[0], now()));
  END IF;
  RETURN NEW;
END
$$ LANGUAGE plpgsql;

-- ---------- Catálogos ----------

CREATE TABLE "Sistema"."Pagina" (
  "PaginaUsys"   varchar(30)  NOT NULL DEFAULT current_user,
  "PaginaDT"     timestamp(6) NOT NULL DEFAULT now(),
  "PaginaId"     smallint     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "PaginaDesc"   varchar(50)  NOT NULL,
  "Descripcion"  varchar(150) NOT NULL
);

CREATE TABLE "Sistema"."ListaPagina" (
  "ListaPaginaUsys"       varchar(50)  NOT NULL DEFAULT current_user,
  "ListaPaginaRV"         integer      NOT NULL DEFAULT 1,
  "ListaPaginaId"         smallint     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "ListaPaginaDesc"       varchar(50)  NOT NULL,
  "ListaPaginaComentario" varchar(500) NOT NULL
);

-- Páginas que forman cada lista
CREATE TABLE "Sistema"."ListaPaginaElemento" (
  "ListaPaginaElementoUsys" varchar(309) NOT NULL DEFAULT current_user,
  "ListaPaginaElementoRV"   integer      NOT NULL DEFAULT 1,
  "ListaPaginaId"           smallint     NOT NULL REFERENCES "Sistema"."ListaPagina",
  "PaginaId"                smallint     NOT NULL REFERENCES "Sistema"."Pagina",
  PRIMARY KEY ("ListaPaginaId", "PaginaId")
);

CREATE TABLE "Sistema"."Permiso" (
  "PermisosUsys" integer     NOT NULL,  -- int en el original (los demás *Usys son varchar)
  "PermisosRV"   integer     NOT NULL DEFAULT 1,
  "PermisoId"    smallint    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "PermisoDesc"  varchar(50) NOT NULL
);

-- Grupo de listas de páginas: un PermisoListaId agrupa varias ListaPagina
CREATE TABLE "Sistema"."PermisoLista" (
  "PermisoListaUsys"     varchar(30) NOT NULL DEFAULT current_user,
  "PermisoListaRV"       integer     NOT NULL DEFAULT 1,
  "PermisoListaId"       integer     NOT NULL,
  "PermisoListaPaginaId" integer     NOT NULL REFERENCES "Sistema"."ListaPagina",
  PRIMARY KEY ("PermisoListaId", "PermisoListaPaginaId")
);

CREATE TABLE "Sistema"."Rol" (
  "RolUsys"         varchar(30) NOT NULL DEFAULT current_user,
  "RolDT"           integer     NOT NULL DEFAULT 1,  -- era timestamp (rowversion) en SQL Server
  "RolId"           smallint    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "RolDesc"         varchar(50) NOT NULL,
  "RolPaginaHomeId" smallint    NOT NULL REFERENCES "Sistema"."Pagina",
  "RolPermisosId"   integer     NOT NULL,  -- -> PermisoLista.PermisoListaId (grupo)
  "RolClassId"      smallint    NOT NULL
);

-- ---------- Nombres ----------

CREATE TABLE "Sistema"."NombrePersonal" (
  "NombrePersonalUsys" varchar(30)  NOT NULL DEFAULT current_user,
  "NombrePersonalRV"   integer      NOT NULL DEFAULT 1,
  "NombrePersonalId"   integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "NombrePersonalDesc" varchar(150) NOT NULL
);

CREATE TABLE "Sistema"."NombreTipo" (
  "NombreTipoUsys" varchar(30) NOT NULL DEFAULT current_user,
  "NombreTipoRV"   integer     NOT NULL DEFAULT 1,
  "NombreTipoId"   smallint    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "NombreTipoDesc" varchar(50) NOT NULL
);

CREATE TABLE "Sistema"."NombreBase" (
  "NombreBaseUsys" varchar(30)  NOT NULL DEFAULT current_user,
  "NombreBaseDT"   timestamp(6) NOT NULL DEFAULT now(),
  "NombreBaseId"   integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "NombreBaseDesc" varchar(50)  NOT NULL
);
CREATE UNIQUE INDEX ON "Sistema"."NombreBase" (lower("NombreBaseDesc"));

-- Partes del nombre de una persona (nombre, apellido paterno, ...)
CREATE TABLE "Sistema"."NombreLista" (
  "NombreListaUsys"  varchar(30) NOT NULL DEFAULT current_user,
  "NombreListaRV"    integer     NOT NULL DEFAULT 1,
  "NombrePersonalId" integer     NOT NULL REFERENCES "Sistema"."NombrePersonal",
  "NombreTipoId"     smallint    NOT NULL REFERENCES "Sistema"."NombreTipo",
  "NombreBaseId"     integer     NOT NULL REFERENCES "Sistema"."NombreBase",
  PRIMARY KEY ("NombrePersonalId", "NombreTipoId")
);

-- ---------- Usuario ----------

CREATE TABLE "Sistema"."Usuario" (
  "UsuarioUsys"              varchar(50)  NOT NULL DEFAULT current_user,
  "UsuarioDT"                timestamp(6) NOT NULL DEFAULT now(),
  "UsuarioId"                smallint     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "UsuarioDesc"              varchar(30)  NOT NULL,  -- nombre de usuario para el login
  "Contraseña"               varchar(100) NOT NULL,  -- hash bcrypt (60 caracteres)
  "UsuarioRolId"             smallint     NOT NULL REFERENCES "Sistema"."Rol",
  "UsuarioPermisosId"        smallint     NOT NULL REFERENCES "Sistema"."Permiso",
  "UsuarioNombreId"          integer      NOT NULL REFERENCES "Sistema"."NombrePersonal",
  "UsuarioPermisosPaginasId" integer      NOT NULL,  -- -> PermisoLista.PermisoListaId (grupo)
  "UsuarioPaginaHomeId"      smallint     NOT NULL REFERENCES "Sistema"."Pagina"
);
-- Login sin distinguir mayúsculas, como Modern_Spanish_CI_AS
CREATE UNIQUE INDEX "UX_Usuario_UsuarioDesc" ON "Sistema"."Usuario" (lower("UsuarioDesc"));

-- ---------- Triggers de auditoría ----------

CREATE TRIGGER tg_pagina              BEFORE UPDATE ON "Sistema"."Pagina"              FOR EACH ROW EXECUTE FUNCTION "Sistema".tg_auditoria('PaginaDT', 'dt');
CREATE TRIGGER tg_listapagina         BEFORE UPDATE ON "Sistema"."ListaPagina"         FOR EACH ROW EXECUTE FUNCTION "Sistema".tg_auditoria('ListaPaginaRV', 'rv');
CREATE TRIGGER tg_listapaginaelemento BEFORE UPDATE ON "Sistema"."ListaPaginaElemento" FOR EACH ROW EXECUTE FUNCTION "Sistema".tg_auditoria('ListaPaginaElementoRV', 'rv');
CREATE TRIGGER tg_permiso             BEFORE UPDATE ON "Sistema"."Permiso"             FOR EACH ROW EXECUTE FUNCTION "Sistema".tg_auditoria('PermisosRV', 'rv');
CREATE TRIGGER tg_permisolista        BEFORE UPDATE ON "Sistema"."PermisoLista"        FOR EACH ROW EXECUTE FUNCTION "Sistema".tg_auditoria('PermisoListaRV', 'rv');
CREATE TRIGGER tg_rol                 BEFORE UPDATE ON "Sistema"."Rol"                 FOR EACH ROW EXECUTE FUNCTION "Sistema".tg_auditoria('RolDT', 'rv');
CREATE TRIGGER tg_nombrepersonal      BEFORE UPDATE ON "Sistema"."NombrePersonal"      FOR EACH ROW EXECUTE FUNCTION "Sistema".tg_auditoria('NombrePersonalRV', 'rv');
CREATE TRIGGER tg_nombretipo          BEFORE UPDATE ON "Sistema"."NombreTipo"          FOR EACH ROW EXECUTE FUNCTION "Sistema".tg_auditoria('NombreTipoRV', 'rv');
CREATE TRIGGER tg_nombrebase          BEFORE UPDATE ON "Sistema"."NombreBase"          FOR EACH ROW EXECUTE FUNCTION "Sistema".tg_auditoria('NombreBaseDT', 'dt');
CREATE TRIGGER tg_nombrelista         BEFORE UPDATE ON "Sistema"."NombreLista"         FOR EACH ROW EXECUTE FUNCTION "Sistema".tg_auditoria('NombreListaRV', 'rv');
CREATE TRIGGER tg_usuario             BEFORE UPDATE ON "Sistema"."Usuario"             FOR EACH ROW EXECUTE FUNCTION "Sistema".tg_auditoria('UsuarioDT', 'dt');
